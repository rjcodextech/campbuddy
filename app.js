// Delegated click tracking for outbound/external links, so every sponsor,
// social, video, useful-link, ticket and organizer-site link is captured
// without hand-wiring each one.
document.addEventListener("click",e=>{
  const a=e.target.closest("a");
  if(!a||!a.href) return;
  const cls=a.className||"";
  const base={link_url:a.href};
  if(cls.includes("video-card")) track("video_click",{...base,video_title:a.querySelector(".video-card__title")?.textContent||""});
  else if(cls.includes("sponsor-chip")) track("sponsor_click",{...base,sponsor_name:(a.querySelector("img")?.alt||a.textContent||"").trim()});
  else if(cls.includes("social-chip")) track("social_click",{...base,platform:a.textContent.trim()});
  else if(cls.includes("ticket-banner__cta")) track("ticket_click",base);
  else if(cls.includes("useful-link")) track("useful_link_click",{...base,link_label:a.querySelector(".useful-link__title")?.textContent||""});
  else if(cls.includes("offer-card")) track("offer_click",{...base,offer_title:a.querySelector(".offer-card__title")?.textContent||""});
  else if(a.target==="_blank") track("outbound_click",base);
});

