function drawBrandedQR(payload){
  return new Promise(resolve=>{
    const qr=qrcode(0,"H");
    qr.addData(payload);
    qr.make();
    const count=qr.getModuleCount();
    const cell=Math.max(6,Math.round(560/(count+8)));
    const margin=cell*4;
    const size=count*cell+margin*2;
    const canvas=document.createElement("canvas");
    canvas.width=size;canvas.height=size;
    const ctx=canvas.getContext("2d");
    ctx.fillStyle="#fffaf4";ctx.fillRect(0,0,size,size);
    ctx.fillStyle="#0d2343";
    for(let r=0;r<count;r++)for(let c=0;c<count;c++)if(qr.isDark(r,c))ctx.fillRect(margin+c*cell,margin+r*cell,cell,cell);
    const markSize=size*0.2, mx=(size-markSize)/2, my=(size-markSize)/2, pad=cell*1.2;
    ctx.fillStyle="#fffaf4";
    roundRect(ctx,mx-pad,my-pad,markSize+pad*2,markSize+pad*2,14);
    ctx.fill();
    const logo=new Image();
    logo.onload=()=>{ctx.drawImage(logo,mx,my,markSize,markSize);resolve(canvas)};
    logo.onerror=()=>resolve(canvas);
    logo.src="./wcr/web/qr-mark.png";
  });
}
function roundRect(ctx,x,y,w,h,r){
  ctx.beginPath();
  ctx.moveTo(x+r,y);
  ctx.arcTo(x+w,y,x+w,y+h,r);
  ctx.arcTo(x+w,y+h,x,y+h,r);
  ctx.arcTo(x,y+h,x,y,r);
  ctx.arcTo(x,y,x+w,y,r);
  ctx.closePath();
}
function slug(s){return String(s).toLowerCase().trim().replace(/[^a-z0-9]+/g,"-").replace(/(^-|-$)/g,"")||"me"}
function downloadCanvas(canvas,name){
  // Analytics only ever gets a static, generic file_name — never the
  // person's real name, even though the actual downloaded file (a local
  // save, sent nowhere) is personalized via slug(name) below.
  track("file_download",{file_name:"campbuddy-card.png",file_extension:"png"});
  canvas.toBlob(blob=>{
    const a=document.createElement("a");
    a.href=URL.createObjectURL(blob);
    a.download=`campbuddy-card-${slug(name)}.png`;
    a.click();
    setTimeout(()=>URL.revokeObjectURL(a.href),1000);
  });
}
function shareCanvas(canvas,payload){
  canvas.toBlob(async blob=>{
    const file=new File([blob],"campbuddy-card.png",{type:"image/png"});
    const shareText=`My CampBuddy card for ${EVENT.name}\n\n${payload}`;
    try{
      if(navigator.canShare && navigator.canShare({files:[file]})){
        await navigator.share({files:[file],title:"My CampBuddy Card",text:shareText});
        track("share",{method:"web_share_api",content_type:"camp_card_qr"});
      }else if(navigator.share){
        await navigator.share({title:"My CampBuddy Card",text:shareText});
        track("share",{method:"web_share_api_text_only",content_type:"camp_card_qr"});
      }else{
        downloadCanvas(canvas,state.card.name||state.name);
        track("share",{method:"download_fallback",content_type:"camp_card_qr"});
        toast("Sharing isn't supported here — downloaded instead");
      }
    }catch(e){/* user cancelled the share sheet */}
  });
}
