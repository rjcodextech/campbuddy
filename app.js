const CACHE_TTL = 6*3600000;

function cacheGet(key){
  try{
    const raw=localStorage.getItem(key);
    if(!raw) return null;
    const {t,data}=JSON.parse(raw);
    if(Date.now()-t>CACHE_TTL) return null;
    return data;
  }catch(e){return null}
}
function cacheSet(key,data){
  try{localStorage.setItem(key,JSON.stringify({t:Date.now(),data}))}catch(e){}
}
async function fetchJSON(url){
  const controller=new AbortController();
  const timer=setTimeout(()=>controller.abort(),8000);
  try{
    const res=await fetch(url,{signal:controller.signal});
    if(!res.ok) return null;
    return await res.json();
  }catch(e){
    return null;
  }finally{
    clearTimeout(timer);
  }
}

function youtubeIdFromLink(link){
  const m=String(link||"").match(/(?:shorts\/|[?&]v=|youtu\.be\/)([a-zA-Z0-9_-]{6,})/);
  return m?m[1]:null;
}
function normalizeVideos(json){
  const items=json&&Array.isArray(json.items)?json.items:null;
  if(!items) return null;
  const out=items.map(it=>{
    const id=youtubeIdFromLink(it.youtube_link);
    if(!id||!it.title) return null;
    return {id,title:String(it.title),type:it.type==="short"?"short":"video",url:it.youtube_link,thumb:it.thumbnail||null};
  }).filter(Boolean);
  return out.length?out.slice(0,10):null;
}

