// Rajasthan-fort tier names (their API) -> the app's platinum/silver/bronze
// tiers (matches the organizer site's own "Nahargarh Fort / Hawa Mahal /
// Jal Mahal" sponsor-tier naming).
const SPONSOR_TIER_MAP={"Nahargarh Fort":{label:"Platinum",cls:"platinum"},"Hawa Mahal":{label:"Silver",cls:"silver"},"Jal Mahal":{label:"Bronze",cls:"bronze"}};
function sponsorsFromLive(ev){
  if(!Array.isArray(ev.event_sponsors)||!ev.event_sponsors.length) return null;
  const groups={};
  ev.event_sponsors.forEach(s=>{
    if(!s.name) return;
    const tier=SPONSOR_TIER_MAP[s.tier]||{label:s.tier||"Sponsors",cls:"bronze"};
    (groups[tier.label]=groups[tier.label]||{tier:tier.label,cls:tier.cls,items:[]}).items.push({name:s.name,url:s.url||"",logo:s.logo||null});
  });
  const order=["Platinum","Silver","Bronze"];
  const out=order.map(t=>groups[t]).filter(Boolean);
  Object.keys(groups).forEach(t=>{if(!order.includes(t))out.push(groups[t])});
  return out.length?out:null;
}
function agendaFromLive(ev){
  if(!Array.isArray(ev.event_agenda)||!ev.event_agenda.length) return null;
  return ev.event_agenda.map(a=>({day:a.day||"",time:a.time||"",title:a.title||"",desc:a.description||""}));
}
function buildEventPatch(ev){
  const patch={};
  if(ev.title) patch.name=ev.title;
  if(ev.event_tagline) patch.tagline=ev.event_tagline;
  if(ev.event_start_date) patch.starts=`${ev.event_start_date}T09:00:00+05:30`;
  if(ev.event_end_date) patch.conference=`${ev.event_end_date}T09:00:00+05:30`;
  if(ev.event_venue_name) patch.venue=ev.event_venue_name;
  if(ev.event_venue_address) patch.address=ev.event_venue_address;
  if(ev.event_hashtag) patch.hashtag=ev.event_hashtag;
  if(ev.event_home_url) patch.officialUrl=ev.event_home_url;
  if(ev.event_tickets_url) patch.ticketUrl=ev.event_tickets_url;
  if(ev.event_venue_directions_url) patch.directionsUrl=ev.event_venue_directions_url;
  if(ev.event_email) patch.contactUrl=`mailto:${ev.event_email}`;
  if(Array.isArray(ev.event_social)&&ev.event_social.length){
    const socials=ev.event_social.filter(s=>s.label&&s.url).map(s=>[s.label,s.url]);
    if(socials.length) patch.socials=socials;
  }
  if(Array.isArray(ev.event_ticket_types)){
    const general=ev.event_ticket_types.find(t=>/^general ticket$/i.test(t.name||"")&&t.status==="available");
    if(general&&general.price) patch.ticketPrice=`${general.price} for both days`;
  }
  return patch;
}

