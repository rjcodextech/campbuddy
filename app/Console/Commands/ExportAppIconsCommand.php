<?php

namespace App\Console\Commands;

use App\Support\LineIcons;
use Illuminate\Console\Command;

/**
 * Writes every website line icon (App\Support\LineIcons) into the native app as one
 * outline path each, so the app draws exactly the website's icons and a new website
 * icon needs no hand copying: native-app/.../ui/LineIconData.kt. A test fails when the
 * file is not what this command would write.
 */
class ExportAppIconsCommand extends Command
{
    protected $signature = 'campbuddy:app-icons {--check : only compare, write nothing}';

    protected $description = 'Write the native app icon paths from the website line icons';

    public const PATH = 'native-app/shared/src/commonMain/kotlin/club/campbuddy/shared/ui/LineIconData.kt';

    /** One icon's SVG elements as a single path string (circles and rectangles become arcs). */
    public static function path(string $markup): string
    {
        preg_match_all('/<(path|circle|rect)\s+([^>]*?)\/?>/', $markup, $elements, PREG_SET_ORDER);
        $parts = [];

        foreach ($elements as [$all, $tag, $attrs]) {
            preg_match_all('/([a-z]+)="([^"]*)"/', $attrs, $pairs, PREG_SET_ORDER);
            $a = [];
            foreach ($pairs as [$p, $name, $value]) {
                $a[$name] = $value;
            }

            if ($tag === 'path') {
                // A path's first moveto is absolute even when written "m"; joined to another path it would turn relative.
                $parts[] = preg_replace('/^\s*m/', 'M', $a['d']);
            } elseif ($tag === 'circle') {
                [$cx, $cy, $r] = [(float) $a['cx'], (float) $a['cy'], (float) $a['r']];
                $parts[] = sprintf('M%s %sa%s %s 0 1 0 %s 0 %s %s 0 1 0 %s 0z', self::n($cx - $r), self::n($cy), self::n($r), self::n($r), self::n(2 * $r), self::n($r), self::n($r), self::n(-2 * $r));
            } else {
                [$x, $y, $w, $h] = [(float) $a['x'], (float) $a['y'], (float) $a['width'], (float) $a['height']];
                $rx = (float) ($a['rx'] ?? 0);
                $parts[] = $rx > 0
                    ? sprintf('M%s %sh%sa%s %s 0 0 1 %s %sv%sa%s %s 0 0 1 %s %sh%sa%s %s 0 0 1 %s %sv%sa%s %s 0 0 1 %s %sz',
                        self::n($x + $rx), self::n($y), self::n($w - 2 * $rx), self::n($rx), self::n($rx), self::n($rx), self::n($rx),
                        self::n($h - 2 * $rx), self::n($rx), self::n($rx), self::n(-$rx), self::n($rx),
                        self::n(-($w - 2 * $rx)), self::n($rx), self::n($rx), self::n(-$rx), self::n(-$rx),
                        self::n(-($h - 2 * $rx)), self::n($rx), self::n($rx), self::n($rx), self::n(-$rx))
                    : sprintf('M%s %sh%sv%sh%sz', self::n($x), self::n($y), self::n($w), self::n($h), self::n(-$w));
            }
        }

        return implode('', $parts);
    }

    private static function n(float $value): string
    {
        return rtrim(rtrim(number_format($value, 3, '.', ''), '0'), '.');
    }

    public static function source(): string
    {
        $lines = [];
        foreach (LineIcons::ICONS as $name => $markup) {
            $lines[] = '    "'.$name.'" to "'.self::path($markup).'",';
        }

        return "package club.campbuddy.shared.ui\n\n"
            ."// GENERATED by `php artisan campbuddy:app-icons` from App\Support\LineIcons.\n"
            ."// Do not edit: change the website icons and run the command (a test checks this file).\n"
            ."internal val WEBSITE_ICON_PATHS = mapOf(\n".implode("\n", $lines)."\n)\n";
    }

    public function handle(): int
    {
        $path = base_path(self::PATH);
        $source = self::source();

        if ($this->option('check')) {
            $same = is_file($path) && str_replace("\r\n", "\n", file_get_contents($path)) === $source;
            $this->line($same ? 'Up to date.' : 'Out of date: run php artisan campbuddy:app-icons');

            return $same ? self::SUCCESS : self::FAILURE;
        }

        file_put_contents($path, $source);
        $this->info('Wrote '.self::PATH);

        return self::SUCCESS;
    }
}
