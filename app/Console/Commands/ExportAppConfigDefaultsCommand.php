<?php

namespace App\Console\Commands;

use App\Support\MobileAppDefaults;
use Illuminate\Console\Command;

/**
 * Writes the native app bundled fallback config (what a phone shows before it
 * has ever reached the server) from the server own defaults, so the two can
 * never drift: native-app/.../DefaultConfigJson.kt. A test fails when the file
 * is not what this command would write.
 */
class ExportAppConfigDefaultsCommand extends Command
{
    protected $signature = 'campbuddy:app-config-defaults {--check : only compare, write nothing}';

    protected $description = 'Write the native app bundled default config from MobileAppDefaults';

    public const PATH = 'native-app/shared/src/commonMain/kotlin/club/campbuddy/shared/data/DefaultConfigJson.kt';

    public static function source(): string
    {
        $json = json_encode(['version' => 0] + MobileAppDefaults::config(), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);

        return "package club.campbuddy.shared.data\n\n"
            ."// GENERATED by `php artisan campbuddy:app-config-defaults` from App\\Support\\MobileAppDefaults.\n"
            ."// Do not edit: change the server defaults and run the command (a test checks this file).\n"
            ."internal const val DEFAULT_CONFIG_JSON = \"\"\"\n{$json}\n\"\"\"\n";
    }

    public function handle(): int
    {
        $path = base_path(self::PATH);
        $source = self::source();

        if ($this->option('check')) {
            $same = is_file($path) && str_replace("\r\n", "\n", file_get_contents($path)) === $source;
            $this->line($same ? 'Up to date.' : 'Out of date: run php artisan campbuddy:app-config-defaults');

            return $same ? self::SUCCESS : self::FAILURE;
        }

        @mkdir(dirname($path), 0777, true);
        file_put_contents($path, $source);
        $this->info('Wrote '.self::PATH);

        return self::SUCCESS;
    }
}
