// Writes the Contribute screen's team list and question tags into the native app from the website's own
// lists (resources/js/attendee/contrib-teams.js), so the two can never say different things.
// Run after changing that file; tests/Feature/NativeKotlinSyncTest.php fails when the app's copy is behind.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const { CONTRIB_TEAMS, CONTRIB_QUESTION_TAGS } = await import(pathToFileURL(resolve(root, 'resources/js/attendee/contrib-teams.js')).href);

const q = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$') + '"';
const list = (a) => 'listOf(' + a.map(q).join(', ') + ')';

let out = `package club.campbuddy.shared.domain

// GENERATED by native-app/scripts/gen-contrib-teams.mjs from resources/js/attendee/contrib-teams.js.
// Do not edit: change the website file and run the script (a test checks this file).

class ContribTeam(
    val id: String,
    val name: String,
    val icon: String,
    val technical: Boolean,
    val matches: List<String>,
    val whoItSuits: String,
    val description: String,
    val beginnerTask: String,
    val atTheTable: String,
)

class ContribTag(val key: String, val label: String)

val CONTRIB_TEAMS = listOf(
`;
for (const t of CONTRIB_TEAMS) {
  out += `    ContribTeam(${q(t.id)}, ${q(t.name)}, ${q(t.icon)}, ${t.technical}, ${list(t.matches)},\n        ${q(t.whoItSuits)},\n        ${q(t.description)},\n        ${q(t.beginnerTask)},\n        ${q(t.atTheTable)}),\n`;
}
out += `)\n\nval CONTRIB_QUESTION_TAGS = listOf(\n`;
for (const t of CONTRIB_QUESTION_TAGS) out += `    ContribTag(${q(t.key)}, ${q(t.label)}),\n`;
out += `)\n`;

writeFileSync(resolve(root, 'native-app/shared/src/commonMain/kotlin/club/campbuddy/shared/domain/ContribTeams.kt'), out);
console.log(`${CONTRIB_TEAMS.length} teams, ${CONTRIB_QUESTION_TAGS.length} tags`);
